//nolint:gochecknoglobals
var userSettableID = suite.Test{
	Name: "user settable id",
	Doc: []string{
		"If method support user settable IDs, when set the resource should",
		"be returned with the provided ID.",
	},

	OnlyIf: suite.OnlyIfs(
		onlyif.HasMethod(aipreflect.MethodTypeCreate),
		onlyif.MethodNotLRO(aipreflect.MethodTypeCreate),
		onlyif.HasUserSettableID,
	),
	Generate: func(f *protogen.GeneratedFile, scope suite.Scope, apiMode util.APIMode) error {
		createMethod, _ := util.StandardMethod(scope.Service, scope.Resource, aipreflect.MethodTypeCreate)
		if util.HasParent(scope.Resource) {
			f.P("parent := ", ident.FixtureNextParent, "(t, false)")
		}
		f.P("userSetID := ", ident.FixtureUserSettableID, "(", strconv.Quote("usersetid"), ")")
		util.MethodCreate{
			Resource:       scope.Resource,
			Method:         createMethod,
			Parent:         "parent",
			UserSettableID: "userSetID",
		}.Generate(f, "req", "msg", "err", ":=", apiMode)
		f.P(ident.AssertNilError, "(t, err)")
		f.P(ident.AssertCheck, "(t, ", ident.StringsHasSuffix, "(msg.GetName(), \"/\" + userSetID))")
		return nil
	},
}

//nolint:gochecknoglobals
var systemGeneratedID = suite.Test{
	Name: "system generated id",
	Doc: []string{
		"If method support user settable IDs that are not required, when not set",
		"the resource should be created with an ID generated by the service,",
		"unique for every resource.",
	},

	OnlyIf: suite.OnlyIfs(
		onlyif.HasMethod(aipreflect.MethodTypeCreate),
		onlyif.MethodNotLRO(aipreflect.MethodTypeCreate),
		onlyif.HasUserSettableID,
		onlyif.UserSettableIDNotRequired,
	),
	Generate: func(f *protogen.GeneratedFile, scope suite.Scope, apiMode util.APIMode) error {
		createMethod, _ := util.StandardMethod(scope.Service, scope.Resource, aipreflect.MethodTypeCreate)
		if util.HasParent(scope.Resource) {
			f.P("parent := ", ident.FixtureNextParent, "(t, false)")
		}
		m := util.MethodCreate{
			Resource:  scope.Resource,
			Method:    createMethod,
			Parent:    "parent",
			WithoutID: true,
		}
		m.Generate(f, "req1", "msg1", "err", ":=", apiMode)
		f.P(ident.AssertNilError, "(t, err)")
		m.Generate(f, "req2", "msg2", "err", ":=", apiMode)
		f.P(ident.AssertNilError, "(t, err)")
		f.P(ident.AssertCheck, "(t, msg1.GetName() != \"\")")
		f.P(ident.AssertCheck, "(t, msg1.GetName() != msg2.GetName())")
		return nil
	},
}

